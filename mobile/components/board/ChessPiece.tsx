// ─── Colour tokens ────────────────────────────────────────────────────────────

interface PieceColors {
  fill: string;
  stroke: string;
  strokeWidth: number;
}

const WHITE_PIECE: PieceColors = { fill: '#FFFFFF', stroke: '#000000', strokeWidth: 1.5 };
const BLACK_PIECE: PieceColors = { fill: '#1A1A1A', stroke: '#FFFFFF', strokeWidth: 1.5 };

// ─── Component ────────────────────────────────────────────────────────────────

export function ChessPiece({ type, color, size }: ChessPieceProps): React.ReactElement {
  const key = `${color}${type}` as keyof typeof PATHS;
  const pathData = PATHS[key] ?? '';
  const colors: PieceColors = color === 'w' ? WHITE_PIECE : BLACK_PIECE;

  return (
    <Svg
      width={size}
      height={size}
      viewBox="0 0 45 45"
      accessibilityLabel={`${color === 'w' ? 'White' : 'Black'} ${type.toUpperCase()}`}
      accessibilityHidden={false}
    >
      <G>
        <Path
          d={pathData}
          fill={colors.fill}
          stroke={colors.stroke}
          strokeWidth={colors.strokeWidth}
          strokeLinecap="round"
          strokeLinejoin="round"
        />
      </G>
    </Svg>
  );
}
